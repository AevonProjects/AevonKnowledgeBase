-- Profiles: public profile fields readable; users cannot grant themselves roles.
drop policy if exists "profiles readable" on public.profiles;
create policy "profiles readable" on public.profiles for select using(true);

-- Categories/tags: everyone reads, admin writes.
drop policy if exists "categories read" on public.categories;
create policy "categories read" on public.categories for select using(true);
drop policy if exists "categories admin insert" on public.categories;
create policy "categories admin insert" on public.categories for insert to authenticated with check(public.is_admin());
drop policy if exists "categories admin update" on public.categories;
create policy "categories admin update" on public.categories for update to authenticated using(public.is_admin()) with check(public.is_admin());
drop policy if exists "categories admin delete" on public.categories;
create policy "categories admin delete" on public.categories for delete to authenticated using(public.is_admin());

drop policy if exists "tags read" on public.tags;
create policy "tags read" on public.tags for select using(true);
drop policy if exists "tags admin insert" on public.tags;
create policy "tags admin insert" on public.tags for insert to authenticated with check(public.is_admin());
drop policy if exists "tags admin update" on public.tags;
create policy "tags admin update" on public.tags for update to authenticated using(public.is_admin()) with check(public.is_admin());
drop policy if exists "tags admin delete" on public.tags;
create policy "tags admin delete" on public.tags for delete to authenticated using(public.is_admin());

-- Published articles public; admins see/write everything.
drop policy if exists "published articles read" on public.articles;
create policy "published articles read" on public.articles for select using(status='published' or public.is_admin());
drop policy if exists "articles admin insert" on public.articles;
create policy "articles admin insert" on public.articles for insert to authenticated with check(public.is_admin() and author_id=auth.uid());
drop policy if exists "articles admin update" on public.articles;
create policy "articles admin update" on public.articles for update to authenticated using(public.is_admin()) with check(public.is_admin());
drop policy if exists "articles admin delete" on public.articles;
create policy "articles admin delete" on public.articles for delete to authenticated using(public.is_admin());

drop policy if exists "article tags read" on public.article_tags;
create policy "article tags read" on public.article_tags for select using(exists(select 1 from public.articles a where a.id=article_id and (a.status='published' or public.is_admin())));
drop policy if exists "article tags admin insert" on public.article_tags;
create policy "article tags admin insert" on public.article_tags for insert to authenticated with check(public.is_admin());
drop policy if exists "article tags admin delete" on public.article_tags;
create policy "article tags admin delete" on public.article_tags for delete to authenticated using(public.is_admin());

-- Likes require Discord-authenticated user and must belong to that user.
drop policy if exists "likes read" on public.article_likes;
create policy "likes read" on public.article_likes for select using(true);
drop policy if exists "likes own insert" on public.article_likes;
create policy "likes own insert" on public.article_likes for insert to authenticated with check(user_id=auth.uid());
drop policy if exists "likes own delete" on public.article_likes;
create policy "likes own delete" on public.article_likes for delete to authenticated using(user_id=auth.uid());

-- Comments: public sees non-hidden; owner can insert own; admin moderates.
drop policy if exists "comments read" on public.comments;
create policy "comments read" on public.comments for select using(not is_hidden or public.is_admin());
drop policy if exists "comments own insert" on public.comments;
create policy "comments own insert" on public.comments for insert to authenticated with check(user_id=auth.uid() and exists(select 1 from public.articles a where a.id=article_id and a.status='published' and a.allow_comments));
drop policy if exists "comments admin update" on public.comments;
create policy "comments admin update" on public.comments for update to authenticated using(public.is_admin()) with check(public.is_admin());
drop policy if exists "comments admin delete" on public.comments;
create policy "comments admin delete" on public.comments for delete to authenticated using(public.is_admin());

