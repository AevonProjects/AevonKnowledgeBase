create extension if not exists pgcrypto;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  display_name text not null default 'Discord user',
  avatar_url text,
  role text not null default 'user' check (role in ('user','admin')),
  created_at timestamptz not null default now()
);

create table if not exists public.categories (
  id uuid primary key default gen_random_uuid(),
  name text not null unique,
  slug text not null unique,
  icon text default '📁',
  sort_order int not null default 0,
  created_at timestamptz not null default now()
);

create table if not exists public.tags (
  id uuid primary key default gen_random_uuid(),
  name text not null unique,
  slug text not null unique,
  emoji text default '🏷️',
  created_at timestamptz not null default now()
);

create table if not exists public.articles (
  id uuid primary key default gen_random_uuid(),
  title text not null,
  slug text not null unique,
  excerpt text,
  content_html text not null default '',
  keywords text default '',
  category_id uuid references public.categories(id) on delete set null,
  author_id uuid references public.profiles(id) on delete set null,
  status text not null default 'draft' check(status in ('draft','published')),
  pinned boolean not null default false,
  featured boolean not null default false,
  allow_comments boolean not null default true,
  published_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.article_tags (
  article_id uuid references public.articles(id) on delete cascade,
  tag_id uuid references public.tags(id) on delete cascade,
  primary key(article_id,tag_id)
);

create table if not exists public.article_likes (
  article_id uuid references public.articles(id) on delete cascade,
  user_id uuid references public.profiles(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key(article_id,user_id)
);

create table if not exists public.comments (
  id uuid primary key default gen_random_uuid(),
  article_id uuid not null references public.articles(id) on delete cascade,
  user_id uuid not null references public.profiles(id) on delete cascade,
  body text not null check(char_length(body) between 1 and 800),
  is_hidden boolean not null default false,
  created_at timestamptz not null default now()
);

create table if not exists public.article_views (
  id bigint generated by default as identity primary key,
  article_id uuid not null references public.articles(id) on delete cascade,
  viewer_hash text,
  created_at timestamptz not null default now()
);

create table if not exists public.search_events (
  id bigint generated by default as identity primary key,
  term text not null check(char_length(term) between 2 and 100),
  user_id uuid references public.profiles(id) on delete set null,
  created_at timestamptz not null default now()
);

create index if not exists idx_articles_status_published on public.articles(status,published_at desc);
create index if not exists idx_comments_article on public.comments(article_id,created_at desc);
create index if not exists idx_search_term on public.search_events(lower(term));
create index if not exists idx_views_article on public.article_views(article_id);

-- Keep updated_at accurate.
create or replace function public.touch_updated_at()
returns trigger language plpgsql set search_path = '' as $$
begin new.updated_at = now(); return new; end $$;
drop trigger if exists articles_touch_updated on public.articles;
create trigger articles_touch_updated before update on public.articles for each row execute function public.touch_updated_at();

-- Automatically create a safe public profile after Discord OAuth.
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer set search_path = ''
as $$
begin
  insert into public.profiles(id,display_name,avatar_url)
  values(
    new.id,
    coalesce(new.raw_user_meta_data->>'full_name',new.raw_user_meta_data->>'name',new.raw_user_meta_data->>'user_name','Discord user'),
    coalesce(new.raw_user_meta_data->>'avatar_url',new.raw_user_meta_data->>'picture')
  )
  on conflict(id) do update set
    display_name=excluded.display_name,
    avatar_url=excluded.avatar_url;
  return new;
end $$;
drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created after insert or update of raw_user_meta_data on auth.users
for each row execute function public.handle_new_user();

create or replace function public.is_admin()
returns boolean
language sql
stable
security definer set search_path = ''
as $$ select exists(select 1 from public.profiles p where p.id=auth.uid() and p.role='admin') $$;

-- Enforce max 3 comments per account, per article, in rolling 24 hours.
create or replace function public.enforce_comment_limit()
returns trigger
language plpgsql
security definer set search_path = ''
as $$
declare n int;
begin
  if new.user_id <> auth.uid() then raise exception 'Invalid user'; end if;
  select count(*) into n from public.comments
  where article_id=new.article_id and user_id=auth.uid() and created_at > now()-interval '24 hours';
  if n >= 3 then raise exception 'COMMENT_LIMIT: Maximum 3 comments per article every 24 hours'; end if;
  return new;
end $$;
drop trigger if exists comments_limit on public.comments;
create trigger comments_limit before insert on public.comments for each row execute function public.enforce_comment_limit();

-- Public helper functions for analytics. They reveal no private data.
create or replace function public.record_search(p_term text)
returns void
language plpgsql
security definer set search_path = ''
as $$
begin
  if char_length(trim(p_term)) between 2 and 100 then
    insert into public.search_events(term,user_id) values(lower(trim(p_term)),auth.uid());
  end if;
end $$;

create or replace function public.record_article_view(p_article_id uuid)
returns void
language plpgsql
security definer set search_path = ''
as $$
begin
  if exists(select 1 from public.articles where id=p_article_id and status='published') then
    insert into public.article_views(article_id) values(p_article_id);
  end if;
end $$;

create or replace view public.popular_searches
with (security_invoker = true)
as
select lower(term) as term,count(*)::bigint as searches
from public.search_events
where created_at > now()-interval '30 days'
group by lower(term)
order by searches desc;

